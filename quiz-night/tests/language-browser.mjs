import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import { SWEDISH_CLUES, SWEDISH_CATEGORIES } from '../dist/questions-sv.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = path.join(root, 'test-results');
await mkdir(out, { recursive: true });
const server = spawn(process.execPath, [path.join(root, 'server.mjs')], { env: { ...process.env, PORT: '4174' }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
const errors = [];
let browser;
try {
  await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Server exited: ${code}`))); });
  const executablePath = process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/chromium', '/usr/bin/google-chrome'].find(existsSync);
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, colorScheme: 'light' });
  page.on('pageerror', error => errors.push(error.message));
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('quiz-night-game-v1')));
  await page.goto('http://127.0.0.1:4174', { waitUntil: 'networkidle' });
  await page.getByLabel('Player 1 name', { exact: true }).fill('Åsa <3');
  await page.getByLabel('Question timer').uncheck();
  await page.getByLabel('Wrong answer penalty').check();
  await page.locator('[data-round="3"]').click();
  await page.getByLabel('Language', { exact: true }).selectOption('sv');
  assert.equal(await page.locator('html').getAttribute('lang'), 'sv');
  assert.equal(await page.getByLabel('Namn på spelare 1', { exact: true }).inputValue(), 'Åsa <3');
  assert.equal(await page.getByLabel('Namn på spelare 2', { exact: true }).inputValue(), 'Spelare 2');
  assert.equal(await page.locator('[data-round="3"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#timer-setting').isChecked(), false);
  assert.equal(await page.locator('#penalty-setting').isChecked(), true);
  await page.screenshot({ path: path.join(out, 'swedish-setup-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Byt till mörkt läge' }).click();
  await page.getByRole('button', { name: 'Slå på ljud' }).click();
  await page.getByRole('button', { name: 'Stäng av ljud' }).click();
  await page.getByRole('button', { name: 'Så spelar ni' }).click();
  assert.ok((await page.locator('#info-dialog').textContent()).includes('Tangentbord'));
  await page.getByRole('button', { name: 'Jag förstår. Nu kör vi.' }).click();
  await page.locator('[data-round="1"]').click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Setup overflows at ${width}px`);
    const bounds = await page.locator('#language-select').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width);
  }
  await page.screenshot({ path: path.join(out, 'swedish-setup-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Nu kör vi', exact: false }).click();
  let g = await saved();
  assert.equal(g.players[0].name, 'Åsa <3');
  assert.equal(await page.locator('.category-header').first().innerText(), `${g.boards[0][0].icon}\n${SWEDISH_CATEGORIES.get(g.boards[0][0].id).name}`);
  const before = JSON.stringify(g);
  await page.getByLabel('Språk', { exact: true }).selectOption('en');
  assert.equal(JSON.stringify(await saved()), before);
  await page.getByLabel('Language', { exact: true }).selectOption('sv');
  assert.equal(JSON.stringify(await saved()), before);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(out, 'swedish-board-mobile.png'), fullPage: true });
  await page.locator('[data-column="0"][data-row="4"]').click();
  const clue = g.boards[0][0].clues[4];
  assert.equal(await page.locator('#clue-heading').textContent(), SWEDISH_CLUES.get(clue.id).question);
  await page.getByRole('button', { name: 'Visa svaret' }).click();
  assert.equal(await page.locator('.answer-panel p').textContent(), SWEDISH_CLUES.get(clue.id).answer);
  await page.screenshot({ path: path.join(out, 'swedish-answer-mobile.png'), fullPage: true });
  // A programmatic language change must also preserve an already revealed clue.
  await page.evaluate(() => { const select = document.querySelector('#language-select'); select.value = 'en'; select.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.equal(await page.locator('#clue-heading').textContent(), clue.question);
  assert.equal(await page.locator('.answer-panel p').textContent(), clue.answer);
  await page.evaluate(() => { const select = document.querySelector('#language-select'); select.value = 'sv'; select.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.equal(await page.locator('.answer-panel p').textContent(), SWEDISH_CLUES.get(clue.id).answer);
  await page.keyboard.press('r');
  assert.equal((await saved()).players[0].score, 1000);
  assert.ok((await page.locator('.player-score').first().textContent()).includes('1\u00a0000'));
  assert.ok((await page.locator('#toast').textContent()).includes('får 1\u00a0000 poäng'));
  await page.locator('[data-column="1"][data-row="0"]').click();
  await page.keyboard.press('Space'); await page.keyboard.press('f');
  assert.equal((await saved()).players[0].score, 800);
  await page.getByRole('button', { name: 'Ångra senaste frågan' }).click();
  assert.equal((await saved()).players[0].score, 1000);
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('lang'), 'sv');
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.equal(await page.locator('#language-select').inputValue(), 'sv');
  await page.getByRole('button', { name: 'Fortsätt spela' }).click();
  assert.equal(await page.locator('.clue-tile.done').count(), 1);
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.screenshot({ path: path.join(out, 'swedish-board-desktop.png'), fullPage: true });
  const remaining = await page.locator('.clue-tile:not(:disabled)').count();
  for (let i = 0; i < remaining; i++) {
    await page.locator('.clue-tile:not(:disabled)').first().click();
    await page.locator('[data-clue="skip"]').click();
  }
  await page.getByRole('button', { name: 'Visa resultatet' }).click();
  assert.equal(await page.locator('#results-title').textContent(), 'Åsa <3 tar hem segern.');
  await page.screenshot({ path: path.join(out, 'swedish-results.png'), fullPage: true });
  await page.getByLabel('Språk', { exact: true }).selectOption('en');
  assert.equal(await page.locator('#results-title').textContent(), 'Åsa <3 takes the crown.');
  await page.getByLabel('Language', { exact: true }).selectOption('sv');
  await page.getByRole('button', { name: 'Samma spelare, nya frågor' }).click();
  assert.equal((await saved()).players[0].name, 'Åsa <3');
  assert.equal((await saved()).players[0].score, 0);
  await page.getByRole('button', { name: 'Spelinställningar' }).click();
  await page.locator('[data-action="start"]').click();
  assert.equal(await page.locator('#info-title').textContent(), 'Börja om?');
  await page.getByRole('button', { name: 'Behåll spelet' }).click();
  const restricted = await browser.newPage();
  restricted.on('pageerror', error => errors.push(error.message));
  await restricted.addInitScript(() => { Storage.prototype.getItem = Storage.prototype.setItem = () => { throw new DOMException('Blocked', 'SecurityError'); }; });
  await restricted.goto('http://127.0.0.1:4174');
  await restricted.getByLabel('Language', { exact: true }).selectOption('sv');
  assert.equal(await restricted.locator('#setup-title').textContent(), 'Spela på ert sätt.');
  assert.deepEqual(errors, []);
  console.log('Swedish browser checks passed: translated questions/answers, settings, custom names, preserved games, language persistence, dark mode, keyboard scoring, penalties, undo, results, rematch, dialogs, narrow screens, and blocked storage.');
} finally {
  await browser?.close(); server.kill();
}
